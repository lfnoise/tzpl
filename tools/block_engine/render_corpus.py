#!/usr/bin/env python3
"""Renders the block-engine reference corpus (devplans/BLOCK_ENGINE_PLAN.md, M0).

Each entry of corpus.tsv is rendered with `tzpl_app --nogui --nrt` into
OUTDIR/<name>.wav, with its log in OUTDIR/logs/<name>.log, and summarized in
OUTDIR/manifest.tsv (frames, peak, RMS, non-finite count, SHA-256).

Engine settings are passed on the command line so a user or project
tzpl-config can't change the renders. --buffer-frames is 64, the block
engine's block size: in NRT, commands sent for immediate execution land on
buffer boundaries, and this keeps that quantization the same before and after.
Random numbers are seeded, both the synths' (TZPL_RNG_SEED) and the
language's (TZPL_LANG_SEED), which scripts draw from while building graphs
and spawning notes. Each worker compiles its synthdefs in
its own TZPL_BUILD directory, so parallel renders never share plugin files.

usage: render_corpus.py [-o OUTDIR] [-f REGEX] [-j JOBS] [--app PATH]
OUTDIR defaults to $TZPL_CORPUS_DIR/<short sha>, where TZPL_CORPUS_DIR
defaults to ~/tzpl-build/block_engine_corpus.
"""

import argparse
import datetime
import hashlib
import math
import os
import queue
import re
import subprocess
import sys
import tempfile
import threading
import time
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from corpus_lib import ROOT, load_corpus, read_wav  # noqa: E402

ENGINE_FLAGS = [
    "--sample-rate", "48000",
    "--buffer-frames", "64",
    "--channels", "2",
    "--input-channels", "0",
    "--silos", "4",
    "--tempo-clocks", "1",
]
BASE_INCLUDES = ["lang/modules", "bridge/modules"]
RNG_SEED = "0x5eed"
LANG_SEED = "0x7a91"
SILENCE_PEAK = 1e-4


def git_sha():
    """The short commit hash, with "+dirty" when tracked files have
    uncommitted changes (the app may have been built from them)."""
    sha = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"],
                         capture_output=True, text=True, check=True).stdout.strip()
    dirty = subprocess.run(["git", "-C", ROOT, "status", "--porcelain", "--untracked-files=no"],
                           capture_output=True, text=True, check=True).stdout.strip()
    return sha + ("+dirty" if dirty else "")


def script_for(e, tmpdir):
    """The .x file to run: the entry's own file, or a generated driver for
    "driver:<module>:<code>" entries."""
    if not e.entry.startswith("driver:"):
        return os.path.join(ROOT, e.entry)
    _, module, code = e.entry.split(":", 2)
    path = os.path.join(tmpdir, f"driver_{e.name}.x")
    with open(path, "w") as f:
        f.write(f"-- generated by render_corpus.py for corpus entry {e.name}\n")
        f.write(f"import {module}.*;\n{code};\n")
    return path


def stats(path):
    w = read_wav(path)
    peak, sumsq, nonfinite = 0.0, 0.0, 0
    for x in w.samples:
        if math.isfinite(x):
            a = abs(x)
            if a > peak:
                peak = a
            sumsq += x * x
        else:
            nonfinite += 1
    n = len(w.samples)
    rms = math.sqrt(sumsq / n) if n else 0.0
    with open(path, "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    return w, peak, rms, nonfinite, sha


def render(e, app, outdir, tmpdir, build_dirs):
    build_dir = build_dirs.get()
    try:
        wav = os.path.join(outdir, f"{e.name}.wav")
        log = os.path.join(outdir, "logs", f"{e.name}.log")
        if os.path.exists(wav):
            os.remove(wav)
        incs = []
        for d in BASE_INCLUDES + e.includes:
            incs += ["-I", os.path.join(ROOT, d)]
        cmd = [app, "--nogui", "--nrt", wav, "--duration", str(e.duration),
               *ENGINE_FLAGS, *incs, script_for(e, tmpdir)]
        env = dict(os.environ, TZPL_RNG_SEED=RNG_SEED, TZPL_LANG_SEED=LANG_SEED,
                   TZPL_BUILD=build_dir, **e.env)
        t0 = time.time()
        with open(log, "w") as lf:
            lf.write(" ".join(cmd) + "\n")
            lf.write(" ".join(f"{k}={v}" for k, v in sorted(e.env.items())) + "\n\n")
            lf.flush()
            try:
                rc = subprocess.run(cmd, cwd=ROOT, env=env, stdout=lf,
                                    stderr=subprocess.STDOUT,
                                    timeout=max(120.0, e.duration * 2 + 60)).returncode
            except subprocess.TimeoutExpired:
                rc = "timeout"
        wall = time.time() - t0
        if not os.path.exists(wav):
            return dict(name=e.name, status=f"fail(rc={rc})", wall=wall)
        w, peak, rms, nonfinite, sha = stats(wav)
        if nonfinite:
            status = "nonfinite"
        elif peak < SILENCE_PEAK:
            status = "silent"
        elif rc != 0:
            status = f"ok(rc={rc})"
        else:
            status = "ok"
        return dict(name=e.name, status=status, rate=w.rate, chans=w.chans,
                    frames=w.frames, peak=peak, rms=rms, nonfinite=nonfinite,
                    sha256=sha, wall=wall)
    finally:
        build_dirs.put(build_dir)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--outdir")
    ap.add_argument("-f", "--filter", help="regex matched against entry names")
    ap.add_argument("-j", "--jobs", type=int, default=max(1, (os.cpu_count() or 2) // 2))
    ap.add_argument("--app", default=os.path.join(
        os.environ.get("TZPL_BUILD_DIR", os.path.join(ROOT, "build")), "app", "tzpl_app"))
    args = ap.parse_args()

    if not os.access(args.app, os.X_OK):
        sys.exit(f"tzpl_app not built at {args.app}")
    sha = git_sha()
    outdir = args.outdir or os.path.join(
        os.environ.get("TZPL_CORPUS_DIR",
                       os.path.expanduser("~/tzpl-build/block_engine_corpus")), sha)
    os.makedirs(os.path.join(outdir, "logs"), exist_ok=True)

    entries = load_corpus()
    if args.filter:
        entries = [e for e in entries if re.search(args.filter, e.name)]
    if not entries:
        sys.exit("no corpus entries selected")

    build_root = os.path.join(outdir, "build")
    build_dirs = queue.Queue()
    for k in range(args.jobs):
        d = os.path.join(build_root, f"w{k}")
        os.makedirs(d, exist_ok=True)
        build_dirs.put(d)

    print(f"rendering {len(entries)} entries into {outdir} with {args.jobs} jobs")
    results, lock = {}, threading.Lock()
    with tempfile.TemporaryDirectory() as tmpdir, ThreadPoolExecutor(args.jobs) as pool:
        def run(e):
            r = render(e, args.app, outdir, tmpdir, build_dirs)
            with lock:
                results[e.name] = r
                print(f"  {r['status']:<12} {e.name}  ({r['wall']:.1f}s)", flush=True)
        list(pool.map(run, entries))

    # Merge with an existing manifest so a filtered run updates only its rows.
    manifest = os.path.join(outdir, "manifest.tsv")
    cols = ["name", "status", "rate", "chans", "frames", "peak", "rms",
            "nonfinite", "sha256", "wall"]
    rows = {}
    if os.path.exists(manifest):
        with open(manifest) as f:
            for line in f:
                if line.startswith("#") or line.startswith("name\t"):
                    continue
                vals = line.rstrip("\n").split("\t")
                rows[vals[0]] = dict(zip(cols, vals))
    rows.update(results)
    order = [e.name for e in load_corpus()]
    with open(manifest, "w") as f:
        f.write(f"# commit {sha}  rendered {datetime.datetime.now().isoformat(timespec='seconds')}\n")
        f.write(f"# app {args.app}\n# engine {' '.join(ENGINE_FLAGS)}  TZPL_RNG_SEED={RNG_SEED}  TZPL_LANG_SEED={LANG_SEED}\n")
        f.write("\t".join(cols) + "\n")
        for name in order + sorted(set(rows) - set(order)):
            if name in rows:
                r = rows[name]
                f.write("\t".join(
                    (f"{r[c]:.6g}" if isinstance(r.get(c), float) else str(r.get(c, "")))
                    for c in cols) + "\n")

    bad = [r for r in results.values() if not r["status"].startswith("ok")]
    print(f"{len(results) - len(bad)}/{len(results)} ok; manifest: {manifest}")
    for r in bad:
        print(f"  {r['status']}: {r['name']}  (log: {outdir}/logs/{r['name']}.log)")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
